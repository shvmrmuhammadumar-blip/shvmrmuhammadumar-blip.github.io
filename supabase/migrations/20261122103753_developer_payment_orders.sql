create or replace function private.finalize_developer_payment_order(
  p_order_id uuid,
  p_provider text,
  p_provider_transaction_id text,
  p_result text,
  p_failure_code text default null
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_order public.developer_payment_orders%rowtype;
  v_previous_type text;
  v_previous_starts_at timestamptz;
  v_previous_expires_at timestamptz;
  v_starts_at timestamptz;
  v_expires_at timestamptz;
  v_action text;
begin
  if p_order_id is null
     or p_provider not in ('payme', 'click')
     or p_result not in ('paid', 'failed', 'cancelled') then
    raise exception using errcode = '22023', message = 'Invalid payment completion payload.';
  end if;

  select *
    into v_order
  from public.developer_payment_orders o
  where o.id = p_order_id
    and o.environment = 'test'
  for update;

  if not found then
    raise exception using errcode = 'P0002', message = 'Payment order not found.';
  end if;

  if v_order.provider <> p_provider then
    raise exception using errcode = '22023', message = 'Payment provider does not match the order.';
  end if;

  if v_order.status = 'paid' then
    return pg_catalog.jsonb_build_object(
      'success', true,
      'already_processed', true,
      'status', 'paid',
      'order_id', v_order.id
    );
  end if;

  if v_order.status <> 'pending' then
    return pg_catalog.jsonb_build_object(
      'success', true,
      'already_processed', true,
      'status', v_order.status,
      'order_id', v_order.id
    );
  end if;

  if p_result = 'paid' then
    if v_order.product_type = 'lumo_plus' then
      select m.membership_type, m.starts_at, m.expires_at
        into v_previous_type, v_previous_starts_at, v_previous_expires_at
      from public.user_memberships m
      where m.user_id = v_order.user_id
      for update;

      if v_previous_type = 'member_premium'
         and v_previous_starts_at <= now()
         and (v_previous_expires_at is null or v_previous_expires_at > now()) then
        if v_previous_expires_at is null then
          raise exception using errcode = '22023',
            message = 'This account already has lifetime Premium.';
        end if;
        v_starts_at := v_previous_starts_at;
        v_expires_at := v_previous_expires_at + interval '30 days';
        v_action := 'renewed';
      else
        v_starts_at := now();
        v_expires_at := v_starts_at + interval '30 days';
        v_action := 'activated';
      end if;

      insert into public.user_memberships (
        user_id, membership_type, starts_at, expires_at,
        source, updated_by, created_at, updated_at
      )
      values (
        v_order.user_id, 'member_premium', v_starts_at, v_expires_at,
        'payment', null, now(), now()
      )
      on conflict (user_id) do update
        set membership_type = excluded.membership_type,
            starts_at = excluded.starts_at,
            expires_at = excluded.expires_at,
            source = 'payment',
            updated_by = null,
            updated_at = now();

      insert into public.user_membership_events (
        user_id, previous_membership_type, membership_type, action,
        starts_at, expires_at, source, actor_id, reason
      )
      values (
        v_order.user_id, v_previous_type, 'member_premium', v_action,
        v_starts_at, v_expires_at, 'payment', null,
        'Developer-only provider test payment; test environment.'
      );
    elsif v_order.product_type = 'gift' then
      insert into public.gift_inventory (
        gift_id, owner_id, source, payment_order_id
      )
      values (
        v_order.gift_id, v_order.user_id, 'purchase', v_order.id
      )
      on conflict (payment_order_id) where payment_order_id is not null do nothing;
    end if;

    update public.developer_payment_orders
      set status = 'paid',
          provider_transaction_id = coalesce(p_provider_transaction_id, provider_transaction_id),
          paid_at = now(),
          updated_at = now(),
          failure_code = null
    where id = v_order.id;

    return pg_catalog.jsonb_build_object(
      'success', true,
      'already_processed', false,
      'status', 'paid',
      'order_id', v_order.id
    );
  end if;

  update public.developer_payment_orders
    set status = p_result,
        provider_transaction_id = coalesce(p_provider_transaction_id, provider_transaction_id),
        failure_code = left(coalesce(p_failure_code, p_result), 120),
        updated_at = now()
  where id = v_order.id;

  return pg_catalog.jsonb_build_object(
    'success', true,
    'already_processed', false,
    'status', p_result,
    'order_id', v_order.id
  );
end;
$function$;

