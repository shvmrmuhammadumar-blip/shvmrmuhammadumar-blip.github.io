begin;

create table if not exists public.developer_payment_orders (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  product_type text not null check (product_type in ('lumo_plus', 'gift')),
  gift_id uuid references public.gift_catalog(id) on delete restrict,
  provider text not null check (provider in ('payme', 'click')),
  environment text not null default 'test' check (environment = 'test'),
  status text not null default 'pending'
    check (status in ('pending', 'paid', 'failed', 'cancelled', 'expired')),
  amount_usd numeric(8,2) not null default 0.10 check (amount_usd = 0.10),
  amount_uzs integer not null default 1200 check (amount_uzs = 1200),
  payme_amount integer not null default 120000 check (payme_amount = 120000),
  currency text not null default 'UZS' check (currency = 'UZS'),
  duration_days integer not null default 30 check (duration_days = 30),
  idempotency_key text not null check (char_length(idempotency_key) between 12 and 128),
  click_prepare_id bigint generated by default as identity unique,
  provider_payment_id text,
  checkout_url text,
  provider_transaction_id text,
  failure_code text,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null default (now() + interval '30 minutes'),
  paid_at timestamptz,
  updated_at timestamptz not null default now(),
  constraint developer_payment_orders_idempotency_unique unique (user_id, idempotency_key),
  constraint developer_payment_orders_product_check check (
    (product_type = 'lumo_plus' and gift_id is null)
    or (product_type = 'gift' and gift_id is not null)
  ),
  constraint developer_payment_orders_paid_check check (
    (status = 'paid') = (paid_at is not null)
  )
);

create index if not exists developer_payment_orders_user_created_idx
  on public.developer_payment_orders (user_id, created_at desc);

create unique index if not exists developer_payment_orders_provider_payment_unique
  on public.developer_payment_orders (provider, provider_payment_id)
  where provider_payment_id is not null;

alter table public.developer_payment_orders enable row level security;
revoke all on public.developer_payment_orders from public, anon, authenticated;
grant select on public.developer_payment_orders to authenticated;
grant select, insert, update, delete on public.developer_payment_orders to service_role;
grant usage, select on sequence public.developer_payment_orders_click_prepare_id_seq to service_role;

drop policy if exists developer_payment_orders_read_developer_own on public.developer_payment_orders;
create policy developer_payment_orders_read_developer_own
  on public.developer_payment_orders
  for select to authenticated
  using (
    user_id = (select auth.uid())
    and private.has_platform_role('developer')
  );

alter table public.gift_inventory
  add column if not exists payment_order_id uuid
  references public.developer_payment_orders(id) on delete set null;

create unique index if not exists gift_inventory_payment_order_unique
  on public.gift_inventory (payment_order_id)
  where payment_order_id is not null;

create or replace function private.create_developer_payment_order(
  p_product_type text,
  p_provider text,
  p_idempotency_key text,
  p_gift_id uuid default null
)
returns public.developer_payment_orders
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_actor uuid := (select auth.uid());
  v_existing public.developer_payment_orders%rowtype;
  v_order public.developer_payment_orders%rowtype;
  v_gift_exists boolean := false;
begin
  if v_actor is null then
    raise exception using errcode = '42501', message = 'Authentication required.';
  end if;

  if not private.has_platform_role('developer') then
    raise exception using errcode = '42501', message = 'Only Developer accounts can use payment test mode.';
  end if;

  if p_product_type not in ('lumo_plus', 'gift')
     or p_provider not in ('payme', 'click') then
    raise exception using errcode = '22023', message = 'Unsupported test purchase.';
  end if;

  if p_idempotency_key is null
     or char_length(p_idempotency_key) < 12
     or char_length(p_idempotency_key) > 128 then
    raise exception using errcode = '22023', message = 'Invalid idempotency key.';
  end if;

  if (p_product_type = 'gift' and p_gift_id is null)
     or (p_product_type = 'lumo_plus' and p_gift_id is not null) then
    raise exception using errcode = '22023', message = 'The selected product is invalid.';
  end if;

  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended(v_actor::text || ':' || p_idempotency_key, 0)
  );

  select *
    into v_existing
  from public.developer_payment_orders o
  where o.user_id = v_actor
    and o.idempotency_key = p_idempotency_key;

  if found then
    if v_existing.product_type <> p_product_type
       or v_existing.provider <> p_provider
       or v_existing.gift_id is distinct from p_gift_id then
      raise exception using errcode = '22023', message = 'This retry key belongs to a different purchase.';
    end if;
    if v_existing.status <> 'pending' then
      raise exception using errcode = '22023', message = 'This payment order has already been completed.';
    end if;
    return v_existing;
  end if;

  if p_product_type = 'gift' then
    select exists (
      select 1 from public.gift_catalog g
      where g.id = p_gift_id and g.is_published = true
    ) into v_gift_exists;
    if not v_gift_exists then
      raise exception using errcode = '22023', message = 'This gift is not available for purchase.';
    end if;
  end if;

  insert into public.developer_payment_orders (
    user_id, product_type, gift_id, provider, environment,
    status, amount_usd, amount_uzs, payme_amount, currency,
    duration_days, idempotency_key
  )
  values (
    v_actor, p_product_type, p_gift_id, p_provider, 'test',
    'pending', 0.10, 1200, 120000, 'UZS',
    30, p_idempotency_key
  )
  returning * into v_order;

  return v_order;
end;
$function$;

revoke all on function private.create_developer_payment_order(text, text, text, uuid)
  from public, anon, authenticated;
grant execute on function private.create_developer_payment_order(text, text, text, uuid)
  to authenticated;

